//! OrbitTE is a Rust-native transfer engine project for AI infrastructure.
//!
//! The capability baseline is Mooncake TENT. OrbitTE is maintained independently
//! under OrbitInfra and is intended to provide byte movement for OrbitKV and
//! other consumers.
//!
//! # Status
//!
//! This initial prerelease establishes the project and package identity. It
//! exposes no transfer API and implements no transport backend yet. It is not
//! ready for application use and does not claim TENT compatibility or performance.
